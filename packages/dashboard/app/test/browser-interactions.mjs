import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_PATH);
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1200, height: 800 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:5173/test/interaction.html');
await page.locator('#workspace-tab-a').waitFor();
const key = 'agent-graph-workspace:["p","a"]';
const saved = () => page.evaluate(key => localStorage.getItem(key), key);
const box = async selector => { const bounds = await page.locator(selector).boundingBox(); assert(bounds); return bounds; };
const drag = async (selector, x, y) => {
  const bounds = await box(selector);
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down(); await page.mouse.move(x, y, { steps: 12 });
};
const pane = await box('[data-pane-id]');
const before = await saved();
await drag('#workspace-tab-b', pane.x + pane.width - 4, pane.y + 150);
assert.equal(await page.locator('.workbench-drop-preview').count(), 1);
assert.equal(await page.locator('.workbench-drag-ghost').count(), 1);
await page.keyboard.press('Escape'); await page.mouse.up();
assert.equal(await page.locator('.workbench-drop-preview, .workbench-drag-ghost').count(), 0);
assert.equal(await saved(), before);
console.log('1: App Escape cancels drag');
await page.locator('#workspace-tab-b').click({ button: 'right' });
await page.keyboard.press('Escape');
assert.equal(await page.locator('.workbench-tab-menu').count(), 0);
console.log('2: App Escape closes menu');
const list = await box('.workbench-tablist');
assert(await page.locator('.workbench-tablist').evaluate(el => el.scrollWidth > el.clientWidth));
await drag('#workspace-tab-b', list.x + list.width - 6, list.y + 12);
await page.waitForTimeout(600);
assert(await page.locator('.workbench-tablist').evaluate(el => el.scrollLeft > 0));
const line = await box('.workbench-drop-end');
assert(line.x >= list.x && line.x + line.width <= list.x + list.width + 1);
await page.mouse.up();
assert(await page.locator('#workspace-tab-b').evaluate(el => { const a = el.getBoundingClientRect(), b = el.closest('.workbench-tablist').getBoundingClientRect(); return a.left >= b.left && a.right <= b.right; }));
console.log('3,4: overflow, autoscroll, visible insertion and active tab');
await page.locator('#workspace-tab-b').click({ button: 'right' });
await page.getByRole('menuitem', { name: 'Split right', exact: true }).click();
const source = await box('[data-pane-id]:has(#workspace-tab-b)');
const splitBefore = await saved();
await drag('#workspace-tab-b', source.x + source.width - 3, source.y + 150);
assert.equal(await page.locator('.workbench-drop-preview').count(), 0);
assert.equal(await page.locator('.workbench-drag-ghost').getAttribute('data-valid'), 'false');
assert.equal(await page.locator('html').getAttribute('data-pointer-drag'), 'not-allowed');
await page.mouse.up(); assert.equal(await saved(), splitBefore);
console.log('5,6: single tab edge rejected, ghost and cursor');
await page.locator('#workspace-tab-b').click({ button: 'right' });
const menu = await box('.workbench-tab-menu');
assert(menu.x >= source.x && menu.x + menu.width <= 1200 && menu.y + menu.height <= 800);
await page.keyboard.press('Escape');
const destination = await box('[data-pane-id]:not(:has(#workspace-tab-b))');
await drag('#workspace-tab-b', destination.x + 50, destination.y + 150);
await page.mouse.click(destination.x + 50, destination.y + 150, { button: 'right' });
assert.equal(await page.locator('.workbench-tab-menu').count(), 0);
await page.keyboard.press('Escape'); await page.mouse.up();
console.log('7: positioned menu and no menu during drag');
const q = await box('[data-project-id="q"] .sidebar-project-row');
await drag('[data-project-id="r"] .sidebar-project-row > a', q.x + 50, q.y + 3);
assert.equal(await page.locator('.project-drop-before').count(), 1);
await page.mouse.move(1100, 700);
assert.equal(await page.locator('.project-drop-before, .project-drop-after').count(), 0);
await page.mouse.move(q.x + 50, q.y + 3); await page.mouse.up();
assert.deepEqual(await page.locator('[data-project-id]').evaluateAll(rows => rows.map(row => row.dataset.projectId)), ['p', 'r', 'q']);
console.log('8: pointer project reorder and cleared insertion');
await page.locator('[data-pane-id]:has(#workspace-tab-a)').getByRole('button', { name: 'Open tab', exact: true }).click();
await page.getByRole('menuitem', { name: 'Conversation', exact: true }).click();
assert.equal(await page.locator('[data-tab-id]').count(), 14);
assert.equal(await page.locator('#workspace-tab-a').getAttribute('aria-selected'), 'true');
const labels = await page.locator('[data-tab-id] [role="tab"]').evaluateAll(tabs => tabs.map(tab => tab.getAttribute('aria-label')));
assert.equal(new Set(labels).size, 14);
console.log('9: existing conversation activated and names distinguished');
assert.deepEqual(errors, []);
await browser.close();
